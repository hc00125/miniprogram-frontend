test('manual random refresh changes seed without same-millisecond collisions and preserves feedback/loading', async t => {
  const h = page({ random: 0, now: 1791723600000 }); t.after(h.unmount)
  h.show(); await h.settle(0, [fixturePlayer(1)])
  const seeds = [h.requests[0].data.shuffle_key]
  for (let i = 0; i < 3; i++) {
    const button = nodes(h.draw()).find(n => n.type === 'button' && text(n) === '刷新')
    button.props.onTap()
    assert.equal(h.state.refreshing.value, true)
    const loading = nodes(h.draw()).find(n => n.type === 'button' && text(n) === '刷新中')
    assert.equal(loading.props.loading, true); assert.equal(loading.props.disabled, true)
    loading.props.onTap()
    assert.equal(h.requests.length, i + 2, 'duplicate refresh remains suppressed')
    seeds.push(h.requests[i + 1].data.shuffle_key)
    assert.match(seeds.at(-1), /^[A-Za-z0-9_-]{1,64}$/)
    assert.notEqual(seeds.at(-1), seeds.at(-2), 'frozen clock and random still require a fresh seed')
    await h.settle(i + 1, [fixturePlayer(i + 2)])
    assert.equal(h.state.refreshing.value, false)
    assert.deepEqual(h.feedback.at(-1), { title: '刷新成功', icon: 'success', duration: 1800 })
  }
  assert.equal(new Set(seeds).size, 4)
  h.elements('discovery-tab')[1].props.onTap(); await h.settle(4, [])
  h.state.handleManualRefresh(); assert.equal(Object.hasOwn(h.requests[5].data, 'shuffle_key'), false)
  await h.settle(5, [])
  h.elements('discovery-tab')[0].props.onTap()
  assert.equal(h.requests[6].data.shuffle_key, seeds.at(-1), 'quality refresh must not rotate the saved random seed')
  await h.settle(6, [])
})

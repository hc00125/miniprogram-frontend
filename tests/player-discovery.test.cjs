test('actual PlayerListParams accepts optional discovery and rejects unsupported modes or non-string seeds', () => {
  const fs = require('node:fs'), path = require('node:path'), ts = require('typescript')
  const { root } = require('./player-discovery-harness.cjs')
  const filename = path.join(root, 'tests/player-discovery-virtual-type-fixture.ts')
  const source = `import type { PlayerListParams } from '../src/api/boss'
const legacy: PlayerListParams = { ordering: '-id' }
const random: PlayerListParams = { discovery: 'random', shuffle_key: 'ascii_1-A' }
const quality: PlayerListParams = { discovery: 'quality' }
// @ts-expect-error unsupported discovery is forbidden
const invalid: PlayerListParams = { discovery: 'top' }
// @ts-expect-error shuffle_key must be a string
const invalidSeed: PlayerListParams = { shuffle_key: 123 }
`
  const options = { noEmit: true, skipLibCheck: true, target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS, baseUrl: root, paths: { '@/*': ['src/*'] } }
  const host = ts.createCompilerHost(options), originalGetSourceFile = host.getSourceFile
  host.fileExists = ((original) => f => f === filename || original(f))(host.fileExists)
  host.readFile = ((original) => f => f === filename ? source : original(f))(host.readFile)
  host.getSourceFile = (f, languageVersion, onError, shouldCreate) => f === filename ? ts.createSourceFile(f, source, languageVersion, true) : originalGetSourceFile(f, languageVersion, onError, shouldCreate)
  const program = ts.createProgram([filename], options, host)
  const errors = ts.getPreEmitDiagnostics(program).filter(d => d.file?.fileName === filename)
  assert.deepEqual(errors.map(e => ts.flattenDiagnosticMessageText(e.messageText, '\n')), [])
  assert.equal(fs.existsSync(filename), false, 'type fixture must stay in memory')
})

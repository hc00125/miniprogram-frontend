// Offline build verification only: never edits real pages.json or uploads.
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { spawnSync } = require('node:child_process')
const root = path.join(__dirname, '..')
const target = fs.mkdtempSync(path.join(process.env.TMPDIR || '/root/.hermes/cache/scratch', 'surcharge-compile-'))
for (const name of ['src', 'static', 'package.json', 'vite.config.ts', 'tsconfig.json']) fs.cpSync(path.join(root, name), path.join(target, name), { recursive: true })
fs.symlinkSync(path.join(root, 'node_modules'), path.join(target, 'node_modules'), 'dir')
const pagesPath = path.join(target, 'src/pages.json')
const pages = JSON.parse(fs.readFileSync(pagesPath, 'utf8'))
pages.pages.push({ path: 'pages/surcharge-foundation-test/index', style: { navigationBarTitleText: '仅隔离编译测试' } })
fs.writeFileSync(pagesPath, JSON.stringify(pages, null, 2))
fs.mkdirSync(path.join(target, 'src/pages/surcharge-foundation-test'), { recursive: true })
fs.writeFileSync(path.join(target, 'src/pages/surcharge-foundation-test/index.vue'), `<template><view><OrderSurchargeSheet :open="false" account-id="" session-key="" order-no="" :player-count="0" /><GiftSheet :open="false" account-id="" :recipient="{ id: '', name: '' }" /></view></template><script setup lang="ts">import OrderSurchargeSheet from '@/components/orders/OrderSurchargeSheet.vue'; import GiftSheet from '@/components/gifts/GiftSheet.vue'</script>`)
const result = spawnSync('npm', ['run', 'build:mp-weixin'], { cwd: target, encoding: 'utf8', env: { ...process.env, NODE_ENV: 'production' }, timeout: 600000 })
fs.writeFileSync(path.join(target, 'build.log'), (result.stdout || '') + (result.stderr || ''))
console.log('Isolated build:', target)
assert.equal(result.status, 0, (result.stderr || '').slice(-4000))
const dist = path.join(target, 'dist/build/mp-weixin')
for (const component of ['orders/OrderSurchargeSheet', 'gifts/GiftSheet', 'gifts/GiftGrid']) {
  for (const ext of ['js', 'json', 'wxml', 'wxss']) assert.ok(fs.statSync(path.join(dist, 'components', `${component}.${ext}`)).size > 0)
}
const wxml = fs.readFileSync(path.join(dist, 'components/orders/OrderSurchargeSheet.wxml'), 'utf8')
const wxss = fs.readFileSync(path.join(dist, 'components/orders/OrderSurchargeSheet.wxss'), 'utf8')
for (const text of ['整单额外加价', '不是每人加价', '暂未开放', '返回原订单查询', '勿重复支付']) assert.ok(wxml.includes(text), text)
assert.match(wxml, /disabled="{{true}}"/)
assert.match(wxss, /safe-area-inset-bottom/)
assert.match(wxss, /min-height:92rpx/)
const giftWxml = fs.readFileSync(path.join(dist, 'components/gifts/GiftSheet.wxml'), 'utf8')
for (const text of ['我的礼物', '购买后赠送', '暂未开放']) assert.ok(giftWxml.includes(text))
const productionApp = JSON.parse(fs.readFileSync(path.join(root, 'dist/build/mp-weixin/app.json'), 'utf8'))
assert.equal(productionApp.pages[0], 'pages/boss/home/index')
assert.ok(!productionApp.pages.some(p => p.includes('foundation-test')))
assert.ok(!fs.existsSync(path.join(root, 'dist/build/mp-weixin/components/orders/OrderSurchargeSheet.js')))
assert.ok(!fs.existsSync(path.join(root, 'dist/build/mp-weixin/components/gifts/GiftSheet.js')))
console.log('Verified isolated surcharge + original gift JS/JSON/WXML/WXSS; production has no test entry or surcharge/gift component.')
